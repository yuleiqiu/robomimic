"""
Annotate each trajectory in an hdf5 dataset with task success.

This script replays each demonstration in the simulator and calls
env.is_success() after each transition. It is useful for datasets generated by
run_trained_agent.py, which store rewards and dones but do not store per-demo
success labels.

Example usage:

    python annotate_dataset_success.py --dataset /path/to/rollouts.hdf5

    python annotate_dataset_success.py --dataset /path/to/rollouts.hdf5 \
        --write_filter_keys --success_filter_key success --failure_filter_key failure
"""
import argparse
import json

import h5py
import numpy as np
from tqdm import tqdm

import robomimic.utils.env_utils as EnvUtils
import robomimic.utils.file_utils as FileUtils
import robomimic.utils.obs_utils as ObsUtils
from robomimic.envs.env_base import EnvBase


def _sorted_demo_keys(demo_keys):
    """
    Sort demo keys numerically when they follow the usual demo_<int> format.
    """
    try:
        return sorted(demo_keys, key=lambda elem: int(elem.split("_")[-1]))
    except ValueError:
        return sorted(demo_keys)


def _json_safe(value):
    """
    Convert common numpy values returned by environments into JSON-safe values.
    """
    if isinstance(value, dict):
        return {k: _json_safe(v) for k, v in value.items()}
    if isinstance(value, np.ndarray):
        return value.tolist()
    if isinstance(value, np.generic):
        return value.item()
    return value


def _initial_state_from_demo(ep_grp, states, is_robosuite_env):
    """
    Construct the reset_to payload for a demonstration.
    """
    initial_state = dict(states=states[0])
    if is_robosuite_env:
        if "model_file" in ep_grp.attrs:
            initial_state["model"] = ep_grp.attrs["model_file"]
        if "ep_meta" in ep_grp.attrs:
            initial_state["ep_meta"] = ep_grp.attrs["ep_meta"]
    return initial_state


def annotate_success_with_actions(env, initial_state, states, actions, check_state_divergence=False):
    """
    Replay actions from the initial state and detect whether task success is reached.

    Args:
        env (EnvBase): environment to replay in
        initial_state (dict): reset_to payload for the initial simulator state
        states (np.array): recorded states, used only for optional divergence checks
        actions (np.array): recorded actions to replay
        check_state_divergence (bool): if True, compare replay states to recorded
            next states after each action where available

    Returns:
        dict: annotation results
    """
    assert isinstance(env, EnvBase)
    assert states.shape[0] == actions.shape[0]

    env.reset_to(initial_state)
    success = False
    success_timestep = -1
    success_metrics = None
    max_state_divergence = 0.0

    for t in range(actions.shape[0]):
        env.step(actions[t])

        if check_state_divergence and t < states.shape[0] - 1:
            state_playback = env.get_state()["states"]
            divergence = np.linalg.norm(states[t + 1] - state_playback)
            max_state_divergence = max(max_state_divergence, float(divergence))

        cur_success_metrics = env.is_success()
        success_metrics = cur_success_metrics
        if cur_success_metrics["task"]:
            success = True
            success_timestep = t
            break

    result = dict(
        success=success,
        success_timestep=success_timestep,
        success_metrics=_json_safe(success_metrics or {}),
        annotation_method="action_playback",
    )
    if check_state_divergence:
        result["max_state_divergence"] = max_state_divergence
    return result


def annotate_success_with_states(env, initial_state, states):
    """
    Detect success by resetting to each recorded state and calling env.is_success().

    This is less reliable for datasets where states are pre-action states and the
    final post-action success state is not stored. Prefer action playback when
    actions are available.
    """
    assert isinstance(env, EnvBase)

    success = False
    success_timestep = -1
    success_metrics = None

    env.reset_to(initial_state)
    for t in range(states.shape[0]):
        env.reset_to({"states": states[t]})
        cur_success_metrics = env.is_success()
        success_metrics = cur_success_metrics
        if cur_success_metrics["task"]:
            success = True
            success_timestep = t
            break

    return dict(
        success=success,
        success_timestep=success_timestep,
        success_metrics=_json_safe(success_metrics or {}),
        annotation_method="state_reset",
    )


def write_filter_key(hdf5_file, key_name, demo_keys):
    """
    Write a mask filter key into an open hdf5 file handle.
    """
    if "mask" not in hdf5_file:
        hdf5_file.create_group("mask")
    hdf5_key = "mask/{}".format(key_name)
    if hdf5_key in hdf5_file:
        del hdf5_file[hdf5_key]
    hdf5_file[hdf5_key] = np.array(demo_keys, dtype="S")


def clip_demo_actions(ep_grp, action_keys, clip_min=-1.0, clip_max=1.0):
    """
    Clip action datasets in a demo group in-place.

    Args:
        ep_grp (h5py.Group): demo group to modify
        action_keys (list): dataset names to clip
        clip_min (float): lower action bound
        clip_max (float): upper action bound

    Returns:
        dict: per-action-key pre / post clipping bounds
    """
    clip_stats = {}
    for action_key in action_keys:
        if action_key not in ep_grp:
            continue

        actions = ep_grp[action_key][()]
        clipped_actions = np.clip(actions, clip_min, clip_max)
        ep_grp[action_key][...] = clipped_actions
        clip_stats[action_key] = dict(
            min_before=float(np.min(actions)),
            max_before=float(np.max(actions)),
            min_after=float(np.min(clipped_actions)),
            max_after=float(np.max(clipped_actions)),
            num_clipped=int(np.sum(actions != clipped_actions)),
        )

    return clip_stats


def annotate_dataset_success(args):
    # Playback does not need real observations, but some env construction paths
    # expect observation utilities to be initialized.
    dummy_spec = dict(
        obs=dict(
            low_dim=["robot0_eef_pos"],
            rgb=[],
        ),
    )
    ObsUtils.initialize_obs_utils_with_obs_specs(obs_modality_specs=dummy_spec)

    env_meta = FileUtils.get_env_metadata_from_dataset(dataset_path=args.dataset)
    env = EnvUtils.create_env_from_metadata(env_meta=env_meta, render=False, render_offscreen=False)
    is_robosuite_env = EnvUtils.is_robosuite_env(env_meta=env_meta)

    mode = "r" if args.dry_run else "r+"
    f = h5py.File(args.dataset, mode)
    try:
        if args.filter_key is not None:
            demos = [elem.decode("utf-8") for elem in np.array(f["mask/{}".format(args.filter_key)])]
        else:
            demos = list(f["data"].keys())
        demos = _sorted_demo_keys(demos)

        if args.n is not None:
            demos = demos[:args.n]

        success_demos = []
        failure_demos = []

        for ep in tqdm(demos):
            ep_grp = f["data/{}".format(ep)]
            states = ep_grp["states"][()]
            initial_state = _initial_state_from_demo(
                ep_grp=ep_grp,
                states=states,
                is_robosuite_env=is_robosuite_env,
            )

            if (not args.states_only) and ("actions" in ep_grp):
                actions = ep_grp["actions"][()]
                result = annotate_success_with_actions(
                    env=env,
                    initial_state=initial_state,
                    states=states,
                    actions=actions,
                    check_state_divergence=args.check_state_divergence,
                )
            else:
                result = annotate_success_with_states(
                    env=env,
                    initial_state=initial_state,
                    states=states,
                )

            if result["success"]:
                success_demos.append(ep)
            else:
                failure_demos.append(ep)

            if not args.dry_run:
                ep_grp.attrs[args.success_attr] = int(result["success"])
                ep_grp.attrs[args.success_timestep_attr] = int(result["success_timestep"])
                ep_grp.attrs["success_metrics"] = json.dumps(result["success_metrics"], indent=4)
                ep_grp.attrs["success_annotation_method"] = result["annotation_method"]
                if "max_state_divergence" in result:
                    ep_grp.attrs["max_state_divergence"] = result["max_state_divergence"]

                if args.clip_actions:
                    clip_stats = clip_demo_actions(
                        ep_grp=ep_grp,
                        action_keys=args.action_keys,
                        clip_min=args.action_clip_min,
                        clip_max=args.action_clip_max,
                    )
                    ep_grp.attrs["action_clip_stats"] = json.dumps(clip_stats, indent=4)

        if args.write_filter_keys and not args.dry_run:
            write_filter_key(f, args.success_filter_key, success_demos)
            write_filter_key(f, args.failure_filter_key, failure_demos)

        print("")
        print("Annotated {} demos".format(len(demos)))
        print("Success: {}".format(len(success_demos)))
        print("Failure: {}".format(len(failure_demos)))
        if args.write_filter_keys and not args.dry_run:
            print("Wrote filter key mask/{}".format(args.success_filter_key))
            print("Wrote filter key mask/{}".format(args.failure_filter_key))
        if args.dry_run:
            print("Dry run only; no hdf5 attributes or filter keys were written.")
        elif args.clip_actions:
            print("Clipped action datasets {} to [{}, {}].".format(
                args.action_keys,
                args.action_clip_min,
                args.action_clip_max,
            ))

    finally:
        f.close()


if __name__ == "__main__":
    parser = argparse.ArgumentParser()

    parser.add_argument(
        "--dataset",
        type=str,
        required=True,
        help="path to hdf5 dataset to annotate in-place",
    )
    parser.add_argument(
        "--filter_key",
        type=str,
        default=None,
        help="optional mask key specifying which demos to annotate",
    )
    parser.add_argument(
        "--n",
        type=int,
        default=None,
        help="optional number of demos to annotate",
    )
    parser.add_argument(
        "--states_only",
        action="store_true",
        help="use recorded states only instead of action playback",
    )
    parser.add_argument(
        "--check_state_divergence",
        action="store_true",
        help="during action playback, compare replay states against recorded next states",
    )
    parser.add_argument(
        "--success_attr",
        type=str,
        default="success",
        help="per-demo hdf5 attribute name for success labels",
    )
    parser.add_argument(
        "--success_timestep_attr",
        type=str,
        default="success_timestep",
        help="per-demo hdf5 attribute name for first success timestep, or -1 for failure",
    )
    parser.add_argument(
        "--write_filter_keys",
        action="store_true",
        help="write hdf5 mask keys for successful and failed demos",
    )
    parser.add_argument(
        "--success_filter_key",
        type=str,
        default="success",
        help="mask key name for successful demos",
    )
    parser.add_argument(
        "--failure_filter_key",
        type=str,
        default="failure",
        help="mask key name for failed demos",
    )
    parser.add_argument(
        "--dry_run",
        action="store_true",
        help="compute labels and print counts without writing to the hdf5 file",
    )
    parser.add_argument(
        "--clip_actions",
        action="store_true",
        help="clip action datasets in-place while annotating",
    )
    parser.add_argument(
        "--action_keys",
        type=str,
        nargs="+",
        default=["actions"],
        help="action dataset names to clip when --clip_actions is set",
    )
    parser.add_argument(
        "--action_clip_min",
        type=float,
        default=-1.0,
        help="minimum action value for --clip_actions",
    )
    parser.add_argument(
        "--action_clip_max",
        type=float,
        default=1.0,
        help="maximum action value for --clip_actions",
    )

    annotate_dataset_success(parser.parse_args())
